#!/usr/bin/env bash
# Generates crates/host/src/ntuser_codes.rs from Wine 9.0's include/ntuser.h (run in WSL; needs ~/wine-src).
H=~/wine-src/include/ntuser.h
fam() { # $1 const name, $2 comment marker
  echo "pub static $1: &[&str] = &["
  sed -n "/^\/\* $2 codes/,/^};/p" $H | grep -E '^\s+[A-Za-z0-9_]+,\s*$' | sed -E 's/^\s+(NtUserCall[A-Za-z]+_)?([A-Za-z0-9_]+),.*/    "\2",/'
  echo "];"
}
{
echo "// @generated by wine/gen_ntuser.sh from Wine 9.0 include/ntuser.h"
fam CALL_NO_PARAM NtUserCallNoParam
fam CALL_ONE_PARAM NtUserCallOneParam
fam CALL_TWO_PARAM NtUserCallTwoParam
fam CALL_HWND NtUserCallHwnd
fam CALL_HWND_PARAM NtUserCallHwndParam
fam KERNEL_CALLBACKS "KernelCallbackTable"
echo "pub static MSG_CALL: &[(u32, &str)] = &["
grep -E "^    NtUser[A-Za-z0-9]+ += 0x[0-9a-f]+," $H | sed -E 's/^ +(NtUser[A-Za-z0-9]+) += (0x[0-9a-f]+),.*/    (\2, "\1"),/'
echo "];"
} > "$1"

#!/usr/bin/env bash
# Generates crates/host/src/reqnames.rs (wineserver request names, index = request id) from Wine 9.0 (run in WSL).
{ echo "// @generated by wine/gen_requests.sh from Wine 9.0 include/wine/server_protocol.h"
  echo "pub static REQUESTS: &[&str] = &["
  sed -n '/^enum request/,/REQ_NB_REQUESTS/p' ~/wine-src/include/wine/server_protocol.h | grep -E '^\s+REQ_[a-z_0-9]+,' | sed -E 's/^\s+REQ_([a-z_0-9]+),.*/    "\1",/'
  echo "];"; } > "$1"

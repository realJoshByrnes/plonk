#!/usr/bin/env python3
"""Generates Plonk's opengl32 stub DLL sources and the host-side name table from wine/gl_spec.txt.

Outputs (paths relative to the repo root):
  wine/gl/opengl32.c      - asm stubs: mov $id,%eax ; call *%fs:0xC0 ; ret $N  (the same gate Wine's syscall stubs use)
  wine/gl/opengl32.def    - undecorated exports
  crates/host/src/glnames.rs - GL: &[(&str, u16)] (index = id & 0xfff in syscall table 2)
"""
import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = []
for line in open(os.path.join(root, "wine", "gl_spec.txt"), encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    name, nbytes = line.split()
    spec.append((name, int(nbytes)))

os.makedirs(os.path.join(root, "wine", "gl"), exist_ok=True)
NL = chr(10)

c = ["/* @generated by wine/gen_gl.py - Plonk opengl32: every entry traps into the host (syscall table 2). */",
     "#include <windows.h>", ""]
for i, (name, nb) in enumerate(spec):
    gid = (2 << 12) | i
    c.append('__asm__(".text\\n.globl _%s@%d\\n_%s@%d:\\n\\tmovl $%d,%%eax\\n\\tcall *%%fs:0xC0\\n\\tret $%d\\n");' % (name, nb, name, nb, gid, nb))
c += ["",
      "/* Extension / core>=1.2 lookups: succeed only for functions this DLL actually exports. */",
      "PROC WINAPI wglGetProcAddress(LPCSTR name) {",
      "    static HMODULE self;",
      "    if (!self) GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT, (LPCSTR)&wglGetProcAddress, &self);",
      "    return self ? (PROC)GetProcAddress(self, name) : 0;",
      "}",
      "BOOL WINAPI DllMain(HINSTANCE h, DWORD why, LPVOID r) { return TRUE; }", ""]
open(os.path.join(root, "wine", "gl", "opengl32.c"), "w", encoding="utf-8", newline=NL).write(NL.join(c))

d = ["LIBRARY opengl32.dll", "EXPORTS"]
for name, nb in spec:
    d.append("    %s = %s@%d" % (name, name, nb))
d.append("    wglGetProcAddress = wglGetProcAddress@4")
open(os.path.join(root, "wine", "gl", "opengl32.def"), "w", encoding="utf-8", newline=NL).write(NL.join(d) + NL)


# ---- the real-Wine variant (wine/gl/opengl32_lx.*): replaces Wine's opengl32.dll; every entry traps into the Plonk kernel with
# int 0x80 (eax = 0x504C1000 + index, ebx -> the arguments). A few entries are C because they need the window behind the DC.
IN_C = {"wglMakeCurrent": 8, "wglSwapBuffers": 4, "glGetString": 4}
lx = ["/* @generated by wine/gen_gl.py - Plonk opengl32 for the real-Wine path. */", "#define WINGDIAPI", "#include <windows.h>", "",
      '__asm__(".text\\n.globl _plonk_host\\n_plonk_host:\\n\\tpushl %ebx\\n\\tmovl 8(%esp),%eax\\n\\tmovl 12(%esp),%ebx\\n\\tint $0x80\\n\\tpopl %ebx\\n\\tret\\n");',
      "extern int plonk_host(unsigned nr, const void *args);", ""]
for i, (name, nb) in enumerate(spec):
    if name in IN_C:
        lx.append("#define IDX_%s %d" % (name, i))
    else:
        lx.append('__asm__(".text\\n.globl _%s@%d\\n_%s@%d:\\n\\tpushl %%ebx\\n\\tleal 8(%%esp),%%ebx\\n\\tmovl $%d,%%eax\\n\\tint $0x80\\n\\tpopl %%ebx\\n\\tret $%d\\n");' % (name, nb, name, nb, 0x504C1000 + i, nb))
lx += ["", open(os.path.join(root, "wine", "gl", "lx_extra.c"), encoding="utf-8").read()]
open(os.path.join(root, "wine", "gl", "opengl32_lx.c"), "w", encoding="utf-8", newline=NL).write(NL.join(lx))
d = ["LIBRARY opengl32.dll", "EXPORTS"]
for name, nb in spec:
    d.append("    %s = %s@%d" % (name, name, nb))
for name, nb in [("wglGetProcAddress", 4), ("wglChoosePixelFormat", 8), ("wglDescribePixelFormat", 16), ("wglSetPixelFormat", 12), ("wglGetPixelFormat", 4)]:
    d.append("    %s = %s@%d" % (name, name, nb))
open(os.path.join(root, "wine", "gl", "opengl32_lx.def"), "w", encoding="utf-8", newline=NL).write(NL.join(d) + NL)

r = ["// @generated by wine/gen_gl.py from wine/gl_spec.txt (name, argument bytes); index = id & 0xfff in syscall table 2.",
     "pub static GL: &[(&str, u16)] = &["]
for name, nb in spec:
    r.append('    ("%s", %d),' % (name, nb))
r.append("];")
open(os.path.join(root, "crates", "host", "src", "glnames.rs"), "w", encoding="utf-8", newline=NL).write(NL.join(r) + NL)
print("generated", len(spec), "entries")

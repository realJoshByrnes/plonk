#!/usr/bin/env bash
# Generates crates/host/src/sysnames.rs from Wine's syscall tables (run in WSL; needs ~/wine-src).
gen() { # $1 header, $2 const name
  echo "pub static $2: &[(&str, u16)] = &["
  grep SYSCALL_ENTRY "$1" | sed -E 's/.*\( *0x[0-9a-f]+, *([A-Za-z0-9_]+), *([0-9]+) *\).*/    ("\1", \2),/'
  echo "];"
}
{ echo "// @generated by wine/gen_syscalls.sh from Wine 9.0 (name, argument bytes); index = syscall id."
  gen ~/wine-src/dlls/ntdll/ntsyscalls.h NT
  gen ~/wine-src/dlls/win32u/win32syscalls.h WIN32U; } > "$1"
